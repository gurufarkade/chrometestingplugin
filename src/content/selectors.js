// Smart, application-agnostic element description + locator generation.
// Produces a ranked list of locator candidates (test-id, role+name, label,
// placeholder, name, aria-label, text, CSS path, XPath) and can resolve them
// back to an element during replay.
(() => {
  const QA = (globalThis.QA = globalThis.QA || {});
  if (QA.sel) return;

  const TEST_ID_ATTRS = ['data-testid', 'data-test-id', 'data-test', 'data-cy', 'data-qa', 'data-automation-id', 'data-automation', 'data-e2e'];
  const ROLE_CANDIDATES = new Set([
    'button', 'link', 'checkbox', 'radio', 'textbox', 'combobox', 'searchbox', 'tab', 'menuitem',
    'menuitemcheckbox', 'menuitemradio', 'option', 'switch', 'slider', 'spinbutton', 'heading', 'treeitem', 'listbox',
  ]);
  const ACTIONABLE =
    'button, a[href], input, select, textarea, label, summary, [role="button"], [role="link"], [role="menuitem"], [role="tab"], [role="option"], [role="checkbox"], [role="radio"], [role="switch"], [role="treeitem"], [role="combobox"], [contenteditable=""], [contenteditable="true"], [onclick], [tabindex]:not([tabindex="-1"])';

  const norm = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
  const clip = (s, n = 80) => (s.length > n ? `${s.slice(0, n - 1)}â€¦` : s);

  function cssEscape(s) {
    return globalThis.CSS?.escape ? CSS.escape(s) : String(s).replace(/([^\w-])/g, '\\$1');
  }
  const attrValue = (v) => String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"');

  /** Heuristic: ids generated by frameworks change between builds/renders. */
  function isStableToken(id) {
    if (!id || id.length > 48) return false;
    if (/^\d/.test(id)) return false;
    if (/\d{4,}/.test(id)) return false;
    if (/[:]/.test(id)) return false; // React useId (:r1:)
    if (/^[0-9a-f]{8}-[0-9a-f]{4}-/i.test(id)) return false;
    if (/^(ember|ext-|gen\d|ui-id|mui-|react-|radix-|headlessui-|__|rc_|el-id-|downshift-|aria-|mat-|cdk-|p-id|jss)/i.test(id)) return false;
    return true;
  }
  function isStableClass(c) {
    if (!c || c.length > 40) return false;
    if (/^(css|sc|jss|emotion|makeStyles|styled|svelte)-/i.test(c)) return false;
    if (/[0-9a-f]{5,}/i.test(c) && /\d/.test(c)) return false; // hashed (abc12f, _3xk9z)
    if (/^_/.test(c)) return false;
    if (/^(is-|has-)?(active|hover|focus|focused|selected|open|disabled|visible|hidden|ng-|v-)/i.test(c)) return false; // state classes
    return /^[a-zA-Z][\w-]*$/.test(c);
  }

  function isVisible(el) {
    if (!el || !el.isConnected) return false;
    if (el.checkVisibility) return el.checkVisibility({ checkOpacity: false, checkVisibilityCSS: true });
    const r = el.getBoundingClientRect();
    const st = getComputedStyle(el);
    return r.width > 0 && r.height > 0 && st.visibility !== 'hidden' && st.display !== 'none';
  }

  // ---------------------------------------------------------------- ARIA

  function getRole(el) {
    const explicit = el.getAttribute('role');
    if (explicit) return explicit.split(/\s+/)[0];
    const tag = el.tagName.toLowerCase();
    switch (tag) {
      case 'a':
        return el.hasAttribute('href') ? 'link' : null;
      case 'button':
        return 'button';
      case 'select':
        return el.multiple || el.size > 1 ? 'listbox' : 'combobox';
      case 'textarea':
        return 'textbox';
      case 'option':
        return 'option';
      case 'summary':
        return 'button';
      case 'img':
        return el.getAttribute('alt') === '' ? 'presentation' : 'img';
      case 'h1': case 'h2': case 'h3': case 'h4': case 'h5': case 'h6':
        return 'heading';
      case 'dialog':
        return 'dialog';
      case 'nav':
        return 'navigation';
      case 'input': {
        const t = (el.getAttribute('type') || 'text').toLowerCase();
        if (['button', 'submit', 'reset', 'image'].includes(t)) return 'button';
        if (t === 'checkbox') return 'checkbox';
        if (t === 'radio') return 'radio';
        if (t === 'range') return 'slider';
        if (t === 'number') return 'spinbutton';
        if (t === 'search') return el.hasAttribute('list') ? 'combobox' : 'searchbox';
        if (['text', 'email', 'tel', 'url', ''].includes(t)) return el.hasAttribute('list') ? 'combobox' : 'textbox';
        return null; // password, date, file, hiddenâ€¦ have no ARIA role
      }
      default:
        return null;
    }
  }

  // textContent (not innerText) to match how Playwright/Cypress compute text:
  // unaffected by CSS text-transform and no forced layout.
  function textOf(el) {
    if (!el.querySelector || !el.querySelector('script,style,noscript')) return norm(el.textContent ?? '');
    const clone = el.cloneNode(true);
    clone.querySelectorAll('script,style,noscript').forEach((n) => n.remove());
    return norm(clone.textContent);
  }

  function labelText(el) {
    if (el.labels && el.labels.length) {
      return norm(
        Array.from(el.labels)
          .map((l) => {
            // Exclude the control's own text (e.g. <label>Name <input></label>)
            const clone = l.cloneNode(true);
            clone.querySelectorAll('input,select,textarea').forEach((n) => n.remove());
            return clone.textContent;
          })
          .join(' '),
      );
    }
    return '';
  }

  function getAccessibleName(el) {
    const labelledBy = el.getAttribute('aria-labelledby');
    if (labelledBy) {
      const t = norm(labelledBy.split(/\s+/).map((id) => document.getElementById(id)?.textContent || '').join(' '));
      if (t) return t;
    }
    const aria = norm(el.getAttribute('aria-label'));
    if (aria) return aria;
    const tag = el.tagName.toLowerCase();
    if (['input', 'select', 'textarea'].includes(tag)) {
      const t = (el.getAttribute('type') || '').toLowerCase();
      if (tag === 'input' && ['button', 'submit', 'reset'].includes(t)) return norm(el.value) || (t === 'submit' ? 'Submit' : t === 'reset' ? 'Reset' : '');
      if (tag === 'input' && t === 'image') return norm(el.getAttribute('alt'));
      const lbl = labelText(el);
      if (lbl) return lbl;
      return norm(el.getAttribute('title')) || norm(el.getAttribute('placeholder'));
    }
    if (tag === 'img') return norm(el.getAttribute('alt')) || norm(el.getAttribute('title'));
    const txt = textOf(el);
    if (txt) return txt;
    // icon-only buttons: <button><svg><title>Close</title></svg></button>
    const svgTitle = el.querySelector?.('svg title');
    if (svgTitle) return norm(svgTitle.textContent);
    const img = el.querySelector?.('img[alt]');
    if (img) return norm(img.getAttribute('alt'));
    return norm(el.getAttribute('title'));
  }

  // ---------------------------------------------------------------- queries

  function queryRole(role, name, root = document) {
    const all = root.querySelectorAll('*');
    const out = [];
    for (const e of all) {
      if (getRole(e) !== role) continue;
      if (name != null && getAccessibleName(e) !== name) continue;
      if (!isVisible(e)) continue;
      out.push(e);
    }
    return out;
  }

  function queryLabel(text) {
    const out = new Set();
    for (const l of document.querySelectorAll('label')) {
      if (norm(l.textContent) === text || labelTextOfLabel(l) === text) {
        const c = l.control;
        if (c && isVisible(c)) out.add(c);
      }
    }
    for (const e of document.querySelectorAll('[aria-label]')) {
      if (norm(e.getAttribute('aria-label')) === text && /^(INPUT|SELECT|TEXTAREA)$/.test(e.tagName) && isVisible(e)) out.add(e);
    }
    return Array.from(out);
  }
  function labelTextOfLabel(l) {
    const clone = l.cloneNode(true);
    clone.querySelectorAll('input,select,textarea').forEach((n) => n.remove());
    return norm(clone.textContent);
  }

  function queryText(tag, text) {
    const out = [];
    for (const e of document.querySelectorAll(tag || '*')) {
      const raw = e.textContent || '';
      // cheap pre-filter before the layout-dependent innerText
      if (raw.length < text.length || (raw.length > text.length * 4 + 40 && norm(raw) !== text)) continue;
      if (textOf(e) === text && isVisible(e)) out.push(e);
    }
    // keep innermost matches only
    return out.filter((e) => !out.some((o) => o !== e && e.contains(o)));
  }

  function queryCss(css) {
    try {
      return Array.from(document.querySelectorAll(css)).filter(isVisible);
    } catch {
      return [];
    }
  }
  function queryCssAll(css) {
    try {
      return Array.from(document.querySelectorAll(css));
    } catch {
      return [];
    }
  }

  function queryXPath(xpath) {
    try {
      const r = document.evaluate(xpath, document, null, XPathResult.ORDERED_NODE_SNAPSHOT_TYPE, null);
      const out = [];
      for (let i = 0; i < r.snapshotLength; i++) out.push(r.snapshotItem(i));
      return out;
    } catch {
      return [];
    }
  }

  function findByCandidate(c) {
    switch (c.type) {
      case 'role':
        return queryRole(c.role, c.name);
      case 'label':
        return queryLabel(c.value);
      case 'text':
        return queryText(c.tag, c.value);
      case 'xpath':
        return queryXPath(c.value);
      default:
        return c.css ? queryCssAll(c.css) : [];
    }
  }

  // ---------------------------------------------------------------- paths

  function cssPath(el) {
    const parts = [];
    let node = el;
    for (let depth = 0; node && node.nodeType === 1 && depth < 8; depth++) {
      const tag = node.tagName.toLowerCase();
      if (tag === 'html') break;
      if (node.id && isStableToken(node.id) && queryCssAll(`#${cssEscape(node.id)}`).length === 1) {
        parts.unshift(`#${cssEscape(node.id)}`);
        break;
      }
      const tAttr = TEST_ID_ATTRS.find((a) => node.getAttribute(a));
      if (tAttr && node !== el) {
        const sel = `[${tAttr}="${attrValue(node.getAttribute(tAttr))}"]`;
        if (queryCssAll(sel).length === 1) {
          parts.unshift(sel);
          break;
        }
      }
      let part = tag;
      const classes = Array.from(node.classList).filter(isStableClass).slice(0, 2);
      if (classes.length) part += classes.map((c) => `.${cssEscape(c)}`).join('');
      const parent = node.parentElement;
      if (parent) {
        const sameTag = Array.from(parent.children).filter((c) => c.tagName === node.tagName);
        if (sameTag.length > 1) part += `:nth-of-type(${sameTag.indexOf(node) + 1})`;
      }
      parts.unshift(part);
      const candidate = parts.join(' > ');
      if (queryCssAll(candidate).length === 1) return candidate;
      node = parent;
    }
    return parts.join(' > ');
  }

  function xPath(el) {
    const parts = [];
    let node = el;
    while (node && node.nodeType === 1) {
      if (node.id && isStableToken(node.id)) {
        parts.unshift(`//*[@id="${node.id}"]`);
        return parts.join('/');
      }
      const tag = node.tagName.toLowerCase();
      const parent = node.parentElement;
      let idx = 1;
      if (parent) {
        const same = Array.from(parent.children).filter((c) => c.tagName === node.tagName);
        idx = same.indexOf(node) + 1;
        parts.unshift(same.length > 1 ? `${tag}[${idx}]` : tag);
      } else parts.unshift(tag);
      node = parent;
    }
    return `/${parts.join('/')}`;
  }

  // ---------------------------------------------------------------- candidates

  function buildCandidates(el) {
    const c = [];
    const tag = el.tagName.toLowerCase();
    const add = (cand, matches) => {
      cand.unique = matches.length === 1 && matches[0] === el;
      if (matches.includes(el) || cand.type === 'css' || cand.type === 'xpath') c.push(cand);
    };

    for (const a of TEST_ID_ATTRS) {
      const v = el.getAttribute(a);
      if (v) {
        const css = `[${a}="${attrValue(v)}"]`;
        add({ type: 'testid', attr: a, value: v, css }, queryCssAll(css));
        break;
      }
    }
    if (el.id && isStableToken(el.id)) {
      const css = `#${cssEscape(el.id)}`;
      add({ type: 'id', value: el.id, css }, queryCssAll(css));
    }
    const role = getRole(el);
    const name = getAccessibleName(el);
    if (role && ROLE_CANDIDATES.has(role) && name && name.length <= 80) {
      add({ type: 'role', role, name }, queryRole(role, name));
    }
    if (/^(input|select|textarea)$/.test(tag)) {
      const lbl = labelText(el) || norm(el.getAttribute('aria-label'));
      if (lbl && lbl.length <= 80) add({ type: 'label', value: lbl }, queryLabel(lbl));
      const ph = el.getAttribute('placeholder');
      if (ph) {
        const css = `${tag}[placeholder="${attrValue(ph)}"]`;
        add({ type: 'placeholder', value: ph, css }, queryCssAll(css));
      }
      const nm = el.getAttribute('name');
      if (nm && isStableToken(nm.replace(/[[\].]/g, ''))) {
        const css = `${tag}[name="${attrValue(nm)}"]`;
        add({ type: 'name', value: nm, css }, queryCssAll(css));
      }
    }
    const aria = el.getAttribute('aria-label');
    if (aria && !c.some((x) => x.type === 'label')) {
      const css = `${tag}[aria-label="${attrValue(aria)}"]`;
      add({ type: 'aria', value: aria, css }, queryCssAll(css));
    }
    const txt = textOf(el);
    if (txt && txt.length <= 60 && !/^(input|select|textarea)$/.test(tag)) {
      add({ type: 'text', tag, value: txt }, queryText(tag, txt));
    }
    const path = cssPath(el);
    add({ type: 'css', value: path, css: path }, queryCssAll(path));
    add({ type: 'xpath', value: xPath(el) }, []);

    // Unique candidates first, keeping the priority order above.
    return [...c.filter((x) => x.unique), ...c.filter((x) => !x.unique)];
  }

  function contextOf(el) {
    const ctx = {};
    const dialog = el.closest('dialog, [role="dialog"], [role="alertdialog"], [aria-modal="true"]');
    if (dialog) ctx.dialog = clip(getAccessibleName(dialog) || norm(dialog.querySelector('h1,h2,h3,h4,[class*="title"]')?.textContent) || 'dialog', 60);
    const form = el.closest('form');
    if (form) {
      ctx.form =
        clip(norm(form.getAttribute('aria-label')) || norm(form.getAttribute('name')) || norm(form.id) || norm(form.querySelector('h1,h2,h3,legend')?.textContent), 60) || 'form';
    }
    const fieldset = el.closest('fieldset');
    if (fieldset) ctx.fieldset = clip(norm(fieldset.querySelector('legend')?.textContent), 60);
    const row = el.closest('tr, [role="row"], li');
    if (row && row !== el) ctx.row = clip(textOf(row), 80);
    const region = el.closest('[role="region"][aria-label], section[aria-label], nav[aria-label], aside[aria-label], header, footer, nav, main');
    if (region) ctx.region = clip(norm(region.getAttribute('aria-label')) || region.tagName.toLowerCase(), 40);
    return ctx;
  }

  /** Climb from a clicked descendant (span/svg/icon) to the element a user meant. */
  function actionableTarget(el) {
    if (!el || el.nodeType !== 1) el = el?.parentElement;
    if (!el) return null;
    const hit = el.closest(ACTIONABLE);
    if (hit && (hit === el || hit.contains(el))) {
      // Don't jump too far (e.g. a whole card with tabindex)
      let depth = 0;
      for (let n = el; n && n !== hit; n = n.parentElement) depth++;
      if (depth <= 5) return hit;
    }
    return el;
  }

  function describe(el) {
    const tag = el.tagName.toLowerCase();
    const r = el.getBoundingClientRect();
    const type = (el.getAttribute('type') || '').toLowerCase() || undefined;
    const testAttr = TEST_ID_ATTRS.find((a) => el.getAttribute(a));
    const html = el.outerHTML.replace(/\svalue="[^"]*"/g, '').slice(0, 300);
    const name = getAccessibleName(el);
    return {
      tag,
      type,
      role: getRole(el) || undefined,
      name: clip(name, 100) || undefined,
      text: clip(textOf(el), 100) || undefined,
      label: clip(labelText(el), 100) || undefined,
      placeholder: el.getAttribute('placeholder') || undefined,
      id: el.id || undefined,
      nameAttr: el.getAttribute('name') || undefined,
      testId: testAttr ? { attr: testAttr, value: el.getAttribute(testAttr) } : undefined,
      href: tag === 'a' ? el.getAttribute('href') : undefined,
      friendly: clip(name || labelText(el) || el.getAttribute('placeholder') || el.getAttribute('name') || el.id || tag, 60),
      context: contextOf(el),
      candidates: buildCandidates(el),
      rect: { x: Math.round(r.x), y: Math.round(r.y), w: Math.round(r.width), h: Math.round(r.height) },
      viewport: { w: innerWidth, h: innerHeight, dpr: devicePixelRatio },
      html,
    };
  }

  QA.sel = {
    describe,
    actionableTarget,
    findByCandidate,
    getRole,
    getAccessibleName,
    isVisible,
    isStableToken,
    isStableClass,
    textOf,
    norm,
  };
})();

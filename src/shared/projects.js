// Projects module — Projects contain Suites; a Suite is an ordered list of
// Scenario ids. Pure: suite operations return new objects; the project export
// builds the files of a runnable Playwright + Cypress test project.
//
// Interface:
//   createProject({ name, baseUrl, description }) -> project
//   addSuite(project, name) -> { project, suite }        (throws on duplicate name)
//   addToSuite / removeFromSuite(project, suiteId, scenarioId) -> project
//   moveInSuite(project, suiteId, scenarioId, delta) -> project
//   deleteSuite(project, suiteId) -> project
//   suitesOf(projects, scenarioId) -> [{ project, suite }]
//   buildProjectFiles(project, scenarios[{session, events, screenshots}], opts) -> [{ name, data }]
//   toProjectBackup / parseProjectBackup
import { buildScenario, toPlaywright, toCypress, toAiContext, envExample, slugify, scrubSecrets } from './exporters.js';

const uid = (p) => `${p}_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 7)}`;

export function createProject({ name, baseUrl = '', description = '' }) {
  if (!String(name || '').trim()) throw new Error('Project name is required');
  return { id: uid('proj'), name: name.trim(), baseUrl: baseUrl.trim(), description, createdAt: Date.now(), suites: [] };
}

const withSuite = (project, suiteId, fn) => ({
  ...project,
  updatedAt: Date.now(),
  suites: project.suites.map((s) => (s.id === suiteId ? fn(s) : s)),
});

export function addSuite(project, name) {
  const clean = String(name || '').trim();
  if (!clean) throw new Error('Suite name is required');
  if (project.suites.some((s) => s.name.toLowerCase() === clean.toLowerCase())) throw new Error(`Suite "${clean}" already exists`);
  const suite = { id: uid('suite'), name: clean, scenarioIds: [] };
  return { project: { ...project, updatedAt: Date.now(), suites: [...project.suites, suite] }, suite };
}

export function addToSuite(project, suiteId, scenarioId) {
  return withSuite(project, suiteId, (s) => (s.scenarioIds.includes(scenarioId) ? s : { ...s, scenarioIds: [...s.scenarioIds, scenarioId] }));
}

export function removeFromSuite(project, suiteId, scenarioId) {
  return withSuite(project, suiteId, (s) => ({ ...s, scenarioIds: s.scenarioIds.filter((x) => x !== scenarioId) }));
}

export function moveInSuite(project, suiteId, scenarioId, delta) {
  return withSuite(project, suiteId, (s) => {
    const ids = [...s.scenarioIds];
    const i = ids.indexOf(scenarioId);
    if (i < 0) return s;
    const j = Math.max(0, Math.min(ids.length - 1, i + delta));
    ids.splice(i, 1);
    ids.splice(j, 0, scenarioId);
    return { ...s, scenarioIds: ids };
  });
}

export function deleteSuite(project, suiteId) {
  return { ...project, updatedAt: Date.now(), suites: project.suites.filter((s) => s.id !== suiteId) };
}

export function suitesOf(projects, scenarioId) {
  return projects.flatMap((project) => project.suites.filter((s) => s.scenarioIds.includes(scenarioId)).map((suite) => ({ project, suite })));
}


function mergeEnv(texts, baseUrl) {
  const vars = new Map([['BASE_URL', `BASE_URL=${baseUrl}`]]);
  for (const t of texts) {
    for (const line of t.split('\n')) {
      const m = line.match(/^([A-Z0-9_]+)=/);
      if (m && !vars.has(m[1])) vars.set(m[1], line);
    }
  }
  return `# Environment for the generated tests\n${[...vars.values()].join('\n')}\n`;
}

/** Files of a runnable test project: one folder per suite, specs numbered in suite order. */
export function buildProjectFiles(project, scenarios, { secrets = 'placeholder', data = 'recommended' } = {}) {
  const byId = new Map(scenarios.map((x) => [x.session.id, x]));
  const files = [];
  const envs = [];
  const suiteNames = [];
  for (const suite of project.suites) {
    const dir = slugify(suite.name);
    suiteNames.push({ name: suite.name, dir });
    suite.scenarioIds.forEach((id, i) => {
      const item = byId.get(id);
      if (!item) return;
      const scn = buildScenario(item.session, item.events, { secrets, data });
      const base = `${String(i + 1).padStart(2, '0')}-${slugify(item.session.name)}`;
      files.push({ name: `tests/${dir}/${base}.spec.ts`, data: toPlaywright(scn) });
      files.push({ name: `cypress/e2e/${dir}/${base}.cy.js`, data: toCypress(scn) });
      files.push({ name: `ai-context/${dir}/${base}.md`, data: toAiContext(scn) });
      envs.push(envExample(scn));
    });
  }
  const baseUrl = project.baseUrl || scenarios[0]?.session.startUrl?.match(/^https?:\/\/[^/]+/)?.[0] || '';
  files.push({
    name: 'playwright.config.ts',
    data: `import { defineConfig } from '@playwright/test';

// Generated by QA Scenario Recorder for "${project.name}". One project per suite:
//   npx playwright test --project=${suiteNames[0]?.dir || 'smoke'}
export default defineConfig({
  testDir: './tests',
  timeout: 60_000,
  retries: process.env.CI ? 1 : 0,
  reporter: [['html', { open: 'never' }], ['list']],
  use: { baseURL: process.env.BASE_URL ?? '${baseUrl}', trace: 'retain-on-failure', screenshot: 'only-on-failure' },
  projects: [
${suiteNames.map((s) => `    { name: '${s.dir}', testDir: './tests/${s.dir}' },`).join('\n')}
  ],
});
`,
  });
  files.push({ name: 'cypress.config.js', data: `const { defineConfig } = require('cypress');\n\nmodule.exports = defineConfig({\n  e2e: { baseUrl: process.env.BASE_URL || '${baseUrl}', specPattern: 'cypress/e2e/**/*.cy.js', supportFile: false },\n});\n` });
  files.push({
    name: 'package.json',
    data: `${JSON.stringify(
      {
        name: slugify(project.name),
        private: true,
        scripts: Object.fromEntries([['test', 'playwright test'], ...suiteNames.map((s) => [`test:${s.dir}`, `playwright test --project=${s.dir}`]), ['cypress', 'cypress run']]),
        devDependencies: { '@playwright/test': '^1.48.0', cypress: '^13.15.0' },
      },
      null,
      2,
    )}\n`,
  });
  files.push({ name: '.env.example', data: mergeEnv(envs, baseUrl) });
  files.push({
    name: 'README.md',
    data: [
      `# ${project.name} — automated tests`,
      '',
      project.description || '',
      `Generated by QA Scenario Recorder from recorded manual scenarios. Base URL: ${baseUrl || '(set BASE_URL)'}`,
      '',
      '## Suites',
      ...project.suites.map((s) => `- **${s.name}** — ${s.scenarioIds.filter((id) => byId.has(id)).map((id) => byId.get(id).session.name).join(', ') || 'empty'}`),
      '',
      '## Run',
      '```bash',
      'npm install && npx playwright install',
      'cp .env.example .env   # fill in credentials',
      'npm test               # all suites',
      ...suiteNames.map((s) => `npm run test:${s.dir}`),
      'npm run cypress        # Cypress version of the same specs',
      '```',
      '',
      '`ai-context/` holds one AI-ready description per scenario to refine the specs with an assistant. `project.qa.json` re-imports into the recorder.',
      '',
    ].join('\n'),
  });
  files.push({ name: 'project.qa.json', data: JSON.stringify(toProjectBackup(project, scenarios, { includeSecrets: secrets === 'include' }), null, 2) });
  return files;
}

export function toProjectBackup(project, scenarios, { includeSecrets = false } = {}) {
  return {
    format: 'qa-scenario-recorder/project',
    version: 1,
    exportedAt: new Date().toISOString(),
    project,
    scenarios: scenarios.map(({ session, events }) => {
      const own = events.filter((e) => (e.runId ?? null) === null);
      return { session: { ...session, runs: [] }, events: includeSecrets ? own : scrubSecrets(own) };
    }),
  };
}

export function parseProjectBackup(json) {
  const data = typeof json === 'string' ? JSON.parse(json) : json;
  if (data?.format !== 'qa-scenario-recorder/project' || !data.project || !Array.isArray(data.scenarios)) throw new Error('Not a QA Scenario Recorder project');
  return data;
}
